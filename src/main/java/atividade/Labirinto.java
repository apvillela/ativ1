    private int linhaInicial = 4;
    private int colunaInicial = 0;
    private int linhaFinal = 21;
    private int colunaFinal = 49;
    private Pilha<Posicao> caminho;

    public void imprimir() {


        for (int i = 0; i < mapa.length; i++) {
            for (int j = 0; j < mapa[i].length; j++) {
                System.out.print(mapa[i][j]);
            }
            System.out.println();
        }
    }


    // DFS com backtracking: a pilha guarda o caminho atual; beco sem saída -> pop
    public void resolver(){
        caminho = new Pilha<>(mapa.length * mapa[0].length);
        caminho.push(new Posicao(linhaInicial, colunaInicial));

        while (!caminho.isEmpty()) {
            Posicao atual = caminho.peek();

            if (atual.linha == linhaFinal && atual.coluna == colunaFinal) {
                limparBecos();
                System.out.println("Resolvido");
                return;
            }

            Posicao proxima = proximaLivre(atual);
            if (proxima != null) {
                mover(proxima);
            } else {
                if (atual.getConteudo() == 'x') {
                    mapa[atual.linha][atual.coluna] = '.';
                }
                caminho.pop();
            }
        }

        limparBecos();
        System.out.println("Sem solução");
    }

    private Posicao proximaLivre(Posicao atual) {
        int[][] direcoes = {{-1, 0}, {0, 1}, {1, 0}, {0, -1}};
        for (int[] d : direcoes) {
            int l = atual.linha + d[0];
            int c = atual.coluna + d[1];
            if (l >= 0 && l < mapa.length && c >= 0 && c < mapa[l].length
                    && (mapa[l][c] == ' ' || mapa[l][c] == 'T')) {
                return new Posicao(l, c);
            }
        }
        return null;
    }

    public void mover(Posicao posicaoDesejada){
        if (posicaoDesejada.getConteudo() == ' ') {
            mapa[posicaoDesejada.linha][posicaoDesejada.coluna] = 'x';
        }
        caminho.push(posicaoDesejada);
    }

    private void limparBecos() {
        for (int i = 0; i < mapa.length; i++) {
            for (int j = 0; j < mapa[i].length; j++) {
                if (mapa[i][j] == '.') {
                    mapa[i][j] = ' ';
                }
            }
        }
    }




    public class Posicao implements Comparable<Posicao> {
        char conteudo;
        int linha;
        int coluna;

        public Posicao(int linha, int coluna) {

            this.linha = linha;
            this.coluna = coluna;
            this.conteudo = mapa[linha][coluna];
        }

        public char getConteudo() {
            this.conteudo = mapa[linha][coluna];
            return conteudo;
        }

        public void setConteudo(char conteudo) {
            this.conteudo = conteudo;
        }

        @Override
        public int compareTo(Posicao o) {
            return 0;
        }
    }
